#!/usr/bin/env python3
"""Send one clearly marked Cadova PDF test to the explicitly authorized address.

Requires SUPABASE_ACCESS_TOKEN and SUPABASE_PROJECT_REF in the environment.
Run only after deploying the quote-document schema and worker. A temporary,
confirmed Auth account signs in normally and exercises the same user RPCs,
private Storage upload and initial-delivery endpoint as the application.
Credentials remain in memory. The helper never queries Resend's read API.
Only resources generated by this invocation are eligible for cleanup.
"""

